from __future__ import annotations

import json
import tempfile
from contextlib import redirect_stderr, redirect_stdout
from io import StringIO
from pathlib import Path

import pytest
from scripts import verify_playwright_browser
from scripts.verify_playwright_browser import (
    BrowserVerificationError,
    browser_payload_evidence,
    browser_tree_sha256,
    cli,
)


def _payload(root: Path) -> Path:
    root.mkdir(parents=True, exist_ok=True)
    (root / "nested").mkdir()
    (root / "browser").write_bytes(b"executable")
    (root / "nested" / "data.pak").write_bytes(b"data")
    return root


def test_tree_digest_binds_paths_sizes_and_contents() -> None:
    with tempfile.TemporaryDirectory() as directory:
        root = _payload(Path(directory) / "payload")
        first = browser_tree_sha256(root)
        assert first == browser_tree_sha256(root)
        (root / "nested" / "data.pak").write_bytes(b"changed")
        assert first != browser_tree_sha256(root)


def test_tree_digest_rejects_empty_or_symlinked_payload() -> None:
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        with pytest.raises(BrowserVerificationError):
            browser_tree_sha256(root)
        target = root / "browser"
        target.write_bytes(b"executable")
        (root / "alias").symlink_to(target)
        with pytest.raises(BrowserVerificationError):
            browser_tree_sha256(root)


def test_the_payload_is_recorded_rather_than_compared() -> None:
    """A payload no maintainer has ever seen is still accepted, and described.

    This is the whole change. The previous digest equality made every
    Playwright bump fail until two platform constants were regenerated by
    hand, while proving only that the payload matched whatever was observed
    first -- which an auto-updating Playwright re-recorded on every bump.
    """

    with tempfile.TemporaryDirectory() as directory:
        root = _payload(Path(directory) / "payload")
        record = browser_payload_evidence(root, "linux-x86_64", "1194")
        assert record["tree_sha256"] == browser_tree_sha256(root)
    assert record["status"] == "recorded"
    assert record["chromium_revision"] == "1194"
    assert record["platform"] == "linux-x86_64"
    assert record["file_count"] == 2
    assert record["total_bytes"] == len(b"executable") + len(b"data")


def test_no_expected_digest_constant_survives() -> None:
    """The pin is gone from the module, not merely unread by one path."""

    assert not hasattr(verify_playwright_browser, "_EXPECTED_TREE_SHA256")


def test_the_evidence_record_carries_no_filesystem_path() -> None:
    with tempfile.TemporaryDirectory() as directory:
        root = _payload(Path(directory) / "payload")
        rendered = json.dumps(browser_payload_evidence(root, "linux-x86_64", "1194"))
    assert str(root) not in rendered
    assert directory not in rendered


def test_a_recorded_payload_is_reported_on_stdout() -> None:
    with tempfile.TemporaryDirectory() as directory:
        root = _payload(Path(directory) / "payload")
        out = StringIO()
        with redirect_stdout(out):
            result = cli(("--path", str(root), "--platform", "darwin-arm64"))
    assert result == 0
    record = json.loads(out.getvalue())
    assert record["schema"] == "browser-payload-evidence-v1"
    assert record["status"] == "recorded"
    assert str(root) not in out.getvalue()


# Four causes that used to be indistinguishable, which is why a failed
# `protected-browser` job reported nothing a reader could act on.
@pytest.mark.parametrize(
    ("target", "requested_platform", "reason"),
    [
        ("missing", "darwin-arm64", "browser_payload_absent"),
        ("empty", "darwin-arm64", "browser_payload_invalid"),
        ("payload", "sunos-vax", "browser_platform_unsupported"),
    ],
)
def test_each_failure_reports_its_own_reason(
    target: str, requested_platform: str, reason: str
) -> None:
    with tempfile.TemporaryDirectory() as directory:
        root = Path(directory)
        (root / "empty").mkdir()
        _payload(root / "payload")
        diagnostics = StringIO()
        with redirect_stderr(diagnostics):
            result = cli(
                ("--path", str(root / target), "--platform", requested_platform)
            )
        assert str(root) not in diagnostics.getvalue()
    assert result == 1
    emitted = json.loads(diagnostics.getvalue())
    assert emitted["status"] == "failed"
    assert emitted["reason"] == reason
    # The point of the change: none of the three lands on the old catch-all.
    assert emitted["reason"] != "browser_verification_failed"


def test_an_unexpected_failure_still_reports_the_catch_all(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """The generic code survives for what the named reasons do not cover."""

    def explode(*_: object, **__: object) -> None:
        raise ValueError("something no reason code anticipates")

    monkeypatch.setattr(verify_playwright_browser, "browser_tree_sha256", explode)
    with tempfile.TemporaryDirectory() as directory:
        root = _payload(Path(directory) / "payload")
        diagnostics = StringIO()
        with redirect_stderr(diagnostics):
            result = cli(("--path", str(root), "--platform", "darwin-arm64"))
    assert result == 1
    emitted = json.loads(diagnostics.getvalue())
    assert emitted["reason"] == "browser_verification_failed"
    assert emitted["status"] == "failed"


class _FakeChromium:
    def __init__(self, failure: Exception | None) -> None:
        self._failure = failure
        self.closed = False

    def launch(self, headless: bool) -> _FakeChromium:
        assert headless is True
        if self._failure is not None:
            raise self._failure
        return self

    def close(self) -> None:
        self.closed = True


class _FakePlaywright:
    def __init__(self, failure: Exception | None) -> None:
        self.chromium = _FakeChromium(failure)

    def __enter__(self) -> _FakePlaywright:
        return self

    def __exit__(self, *_: object) -> None:
        return None


def _fake_playwright(
    monkeypatch: pytest.MonkeyPatch, failure: Exception | None
) -> _FakePlaywright:
    fake = _FakePlaywright(failure)
    monkeypatch.setattr(
        verify_playwright_browser, "sync_playwright", lambda: fake, raising=True
    )
    return fake


def test_the_launch_probe_starts_and_stops_the_installed_browser(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Recording the payload never starts it, so this is a separate claim.

    `_installed_payload` resolves an executable path and digests a tree; a
    runner image missing one of Chromium's shared libraries passes both. The
    public gate stopped installing those libraries when it dropped
    `playwright install --with-deps` (#772), so the launch is what now proves
    the assumption that the image supplies them.
    """

    fake = _fake_playwright(monkeypatch, None)
    emitted = StringIO()
    with redirect_stdout(emitted):
        result = cli(("--launch", "--platform", "linux-x86_64"))
    assert result == 0
    assert fake.chromium.closed is True
    record = json.loads(emitted.getvalue())
    assert record["status"] == "launched"
    assert record["platform"] == "linux-x86_64"
    # The probe answers one question and pays for nothing else: no digest, no
    # file count, no byte total over a two-hundred-megabyte tree.
    assert "tree_sha256" not in record


def test_a_failed_launch_reports_its_own_reason_and_keeps_the_message(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """The missing library names itself, and the code says where to look.

    A launch that fails on the image's libraries is not a browser-tier defect,
    and the whole point of the separate step is that a reader can tell the two
    apart without reading the tier. The reason code carries that, and
    Playwright's own message -- the only actionable half -- survives beside it
    rather than being swallowed by the catch-all.
    """

    _fake_playwright(
        monkeypatch,
        RuntimeError("Host system is missing dependencies: libnss3.so"),
    )
    diagnostics = StringIO()
    with redirect_stderr(diagnostics):
        result = cli(("--launch", "--platform", "linux-x86_64"))
    assert result == 1
    reported = diagnostics.getvalue().splitlines()
    assert reported[0] == (
        "chromium launch failed: Host system is missing dependencies: libnss3.so"
    )
    emitted = json.loads(reported[1])
    assert emitted["reason"] == "browser_launch_failed"
    assert emitted["status"] == "failed"
