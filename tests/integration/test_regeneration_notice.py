_FIRST_FINISHED = 1_700_000_000
_SECOND_FINISHED = 1_700_000_500
# The book's library, as the settings name it.
_CONFIGURED = frozenset({("primary", "ebooks")})
_PRODUCER = "f" * 64


def _store_mode() -> ApplicationConfiguration:
    """No configuration file: the command reads the store alone."""
    raise FileNotFoundError


def _regenerate(path: Path, finished_at: int) -> None:
    """An upgrade's derived partition, regenerated by the command's store."""
    assert rewrite(path, "UPDATE ledger_meta SET derived_version=2") == 1
    outcome = regenerate_derived(
        SQLiteRegenerationStore(path, lambda: finished_at),
        retire_pending=False,
        configuration=_store_mode,
    )
    assert outcome.kind == "regenerated", outcome


def _reopened(root: Path, resolved: ResolvedMetadataPolicy) -> OwnerStore:
    store = OwnerStore(root, None)
    store.resolved = resolved
    return store


def _read_at_this_epoch(store: OwnerStore, report: MetadataReport) -> str:
    """Read the book again as a scan does after a regeneration: its
    proposals at the ledger's epoch, admitted and projected, so the question
    check runs on its first new case."""
    connection = store.repository._connection
    current = connection.execute(
        "SELECT report_id FROM current_metadata_reports WHERE connection_name=? "
        "AND library_name=? AND item_id=? AND file_identity=?",
        (
            report.target.connection,
            report.target.library,
            report.target.item,
            report.file.identity,
        ),
    ).fetchone()
    store.repository.publish(report, lambda: True, current and current[0])
    resolved = store.resolved
    assert resolved is not None
    proposal = evaluate_report(
        report,
        resolved.resolved_id,
        human_review_destinations(resolved),
        derived_epoch=derived_epoch(connection),
    )
    store.repository.publish_proposal(proposal)
    admitted = json.loads(store.repository.admit_review_case(proposal))
    assert admitted["status"] in {"admitted", "superseded"}, admitted
    case = store.load(admitted["review_case_id"])
    store.repository.persist_shadow_outcome(case.review_case_id, store.clock())
    return case.review_case_id


def _notices(store: OwnerStore) -> RegenerationNoticeStore:
    return store.repository.regeneration_notice_store()


def _outcomes(store: OwnerStore) -> list[tuple[str, int]]:
    return [
        tuple(row)
        for row in store.repository._connection.execute(
            "SELECT outcome,derived_epoch FROM carry_outcomes "
            "ORDER BY derived_epoch,checked_at"
        )
    ]


def test_no_regeneration_yet_reads_no_notice_and_dismisses_nothing(
    tmp_path: Path,
) -> None:
    store, report, _ = _store(tmp_path, posture="preview")
    try:
        store.publish(report)
        store.decide("keep_current")
        assert _notices(store).read_regeneration_notice(_CONFIGURED) is None
        with pytest.raises(RegenerationNoticeDismissalInvalid):
            _notices(store).dismiss_regeneration_notice(1, _FIRST_FINISHED)
        assert store.repository._connection.execute(
            "SELECT count(*) FROM regeneration_notice_dismissals"
        ).fetchone() == (0,)
    finally:
        store.close()


def test_the_notice_counts_its_first_new_cases_and_a_second_regeneration_supersedes(
    tmp_path: Path,
) -> None:
    """Regeneration 1: the kept answer is not yet checked until its book is
    read again, then carried there (kept); a later case asking the carried
    answer again does not count. Its notice is dismissed once.
    Regeneration 2: the carried answer, given before it, meets a library
    whose title changed, so it is asked again, once however many cases ask;
    the new notice is its own, undismissed, and counts nothing of the
    first."""
    root = tmp_path / "data"
    root.mkdir(mode=0o700)
    path = root / "owner.sqlite"
    store, report, _ = _store(root, posture="preview")
    store.publish(report)
    store.decide("keep_current")
    resolved = store.resolved
    assert resolved is not None
    store.close()

    _regenerate(path, _FIRST_FINISHED)
    store = _reopened(root, resolved)
    try:
        assert _notices(store).read_regeneration_notice(
            _CONFIGURED
        ) == RegenerationNotice(
            regeneration_id=1,
            derived_epoch=1,
            finished_at=_FIRST_FINISHED,
            kept=0,
            asked_again=0,
            not_yet_checked=1,
            dismissed=False,
        )
        _read_at_this_epoch(store, report)
        assert _outcomes(store) == [("carried", 1)]
        first = _notices(store).read_regeneration_notice(_CONFIGURED)
        assert first == RegenerationNotice(1, 1, _FIRST_FINISHED, 1, 0, 0, False)
        # The carried answer was given after the regeneration, so a later case
        # asking it again is no first new case of it.
        _read_at_this_epoch(store, rewritten(report, title="Another Title"))
        assert _outcomes(store) == [("carried", 1), ("target_changed", 1)]
        assert _notices(store).read_regeneration_notice(_CONFIGURED) == first

        # One dismissal, never before the regeneration finished.
        with pytest.raises(RegenerationNoticeDismissalInvalid):
            _notices(store).dismiss_regeneration_notice(1, _FIRST_FINISHED - 1)
        with pytest.raises(RegenerationNoticeDismissalInvalid):
            _notices(store).dismiss_regeneration_notice(2, _FIRST_FINISHED)
        assert _notices(store).dismiss_regeneration_notice(1, _FIRST_FINISHED + 5)
        assert not _notices(store).dismiss_regeneration_notice(1, _FIRST_FINISHED + 9)
        assert store.repository._connection.execute(
            "SELECT regeneration_id,dismissed_at FROM regeneration_notice_dismissals"
        ).fetchall() == [(1, _FIRST_FINISHED + 5)]
        notice = _notices(store).read_regeneration_notice(_CONFIGURED)
        assert notice is not None and notice.dismissed
    finally:
        store.close()
    assert opens(path)

    _regenerate(path, _SECOND_FINISHED)
    store = _reopened(root, resolved)
    try:
        second = _notices(store).read_regeneration_notice(_CONFIGURED)
        assert second == RegenerationNotice(2, 2, _SECOND_FINISHED, 0, 0, 1, False)
        first_case = _read_at_this_epoch(
            store, rewritten(report, title="Another Title")
        )
        assert _outcomes(store)[2:] == [("target_changed", 2)]
        assert _notices(store).read_regeneration_notice(
            _CONFIGURED
        ) == RegenerationNotice(2, 2, _SECOND_FINISHED, 0, 1, 0, False)
        # Only the first new case counts: a later case of the same epoch
        # asking again leaves the counts as they are.
        _read_at_this_epoch(store, rewritten(report, title="Third Title"))
        assert _outcomes(store)[2:] == [("target_changed", 2)] * 2
        assert _notices(store).read_regeneration_notice(
            _CONFIGURED
        ) == RegenerationNotice(2, 2, _SECOND_FINISHED, 0, 1, 0, False)

        # Negative control: a field with nothing to answer on is not asked
        # again in the notice's count (contract R1), read on the derived fact.
        connection = store.repository._connection
        connection.execute(
            "UPDATE review_case_field_facts SET has_owner_decision_actions=0 "
            "WHERE review_case_id=? AND destination='title'",
            (first_case,),
        )
        notice = _notices(store).read_regeneration_notice(_CONFIGURED)
        assert notice is not None and notice.asked_again == 0
    finally:
        store.close()


def _discovery(store: OwnerStore, at: int) -> Any:
    """Start a scan of the book's library and claim its discovery."""
    store.repository.request_review_scan("primary", "ebooks", "lib-1", _PRODUCER, at)
    action = store.repository.claim_review_pipeline_action(at + 1)
    assert action is not None and action.stage == "discovery"
    return action


def _scans(store: OwnerStore) -> list[tuple[str, str | None]]:
    return [
        tuple(row)
        for row in store.repository._connection.execute(
            "SELECT state,discovery_failure FROM review_preparation_scans"
        )
    ]


def _unread(item_id: str) -> CatalogueEntry:
    """A work the library lists but cannot give: it gets preparation work,
    which fails, so no new case comes yet."""
    return CatalogueEntry(
        "primary",
        "ebooks",
        "lib-1",
        item_id,
        1,
        "Synthetic work",
        ("Ada Example",),
        True,
        False,
        "needs-attention",
        unread="no_media",
    )


@pytest.mark.parametrize(
    "listed",
    [(), (_unread("item-2"),)],
    ids=["library_now_empty", "another_work_listed"],
)
def test_an_answer_whose_work_a_completed_scan_left_out_stops_counting(
    tmp_path: Path, listed: tuple[CatalogueEntry, ...]
) -> None:
    """An answer still counts while its library's first scan since the
    regeneration runs, and stops once that scan completed without its work:
    no new case can come for it (review round 1, finding 3). A scan whose
    discovery failed, or one that lists the work, keeps it counting."""
    root = tmp_path / "data"
    root.mkdir(mode=0o700)
    path = root / "owner.sqlite"
    store, report, _ = _store(root, posture="preview")
    assert {(report.target.connection, report.target.library)} == _CONFIGURED
    store.publish(report)
    store.decide("keep_current")
    resolved = store.resolved
    assert resolved is not None
    store.close()
    _regenerate(path, _FIRST_FINISHED)
    store = _reopened(root, resolved)
    counting = RegenerationNotice(1, 1, _FIRST_FINISHED, 0, 0, 1, False)
    try:
        notices = _notices(store)
        assert notices.read_regeneration_notice(_CONFIGURED) == counting
        # A discovery that fails tells nothing about the work.
        failed = _discovery(store, _FIRST_FINISHED + 10)
        store.repository.fail_review_pipeline_action(
            failed, "library_unavailable", False, _FIRST_FINISHED + 12
        )
        assert _scans(store) == [("completed_with_failures", "library_unavailable")]
        assert notices.read_regeneration_notice(_CONFIGURED) == counting
        # The first scan that can list the work is still discovering.
        action = _discovery(store, _FIRST_FINISHED + 20)
        assert notices.read_regeneration_notice(_CONFIGURED) == counting
        store.repository.complete_review_discovery(
            action, 1, "a" * 64, listed, _FIRST_FINISHED + 22
        )
        assert (
            store.repository.claim_review_pipeline_action(_FIRST_FINISHED + 23) is None
        )
        assert _scans(store) == [("completed", None)]
        assert notices.read_regeneration_notice(_CONFIGURED) == RegenerationNotice(
            1, 1, _FIRST_FINISHED, 0, 0, 0, False
        )
    finally:
        store.close()
    assert opens(path)


def test_an_answer_whose_listed_work_cannot_be_read_stops_counting(
    tmp_path: Path,
) -> None:
    """A completed scan that lists the work but cannot give it fails the
    work for good: no new case comes from it, so the answer stops counting
    (review round 2, M1). It counts until that scan completes."""
    root = tmp_path / "data"
    root.mkdir(mode=0o700)
    path = root / "owner.sqlite"
    store, report, _ = _store(root, posture="preview")
    store.publish(report)
    store.decide("keep_current")
    resolved = store.resolved
    assert resolved is not None
    store.close()
    _regenerate(path, _FIRST_FINISHED)
    store = _reopened(root, resolved)
    try:
        action = _discovery(store, _FIRST_FINISHED + 20)
        assert _notices(store).read_regeneration_notice(
            _CONFIGURED
        ) == RegenerationNotice(1, 1, _FIRST_FINISHED, 0, 0, 1, False)
        store.repository.complete_review_discovery(
            action, 1, "a" * 64, (_unread(report.target.item),), _FIRST_FINISHED + 22
        )
        assert (
            store.repository.claim_review_pipeline_action(_FIRST_FINISHED + 23) is None
        )
        assert _scans(store) == [("completed", None)]
        assert store.repository._connection.execute(
            "SELECT state,failure_code FROM review_preparation_work WHERE item_id=?",
            (report.target.item,),
        ).fetchall() == [("failed", "item_no_media")]
        assert _notices(store).read_regeneration_notice(
            _CONFIGURED
        ) == RegenerationNotice(1, 1, _FIRST_FINISHED, 0, 0, 0, False)
    finally:
        store.close()
    assert opens(path)


# --- A work the first scan since the regeneration prepares -------------------

# After the regeneration: more than 30 days after the answer was written.
_LATER = KEPT_CASE_SECONDS + 100


def _written_answer(library: Library, tmp_path: Path) -> str:
    """The owner's authors answer, written to the library and verified."""
    owner = accept(library.case(), "authors", "owner-answers-authors", 11)
    library.root.record_human_decision(owner)
    library.root.grant_field_effect_consents("primary", ("ebooks",), ("authors",), 12)
    scheduler, service, target = applier(library, tmp_path)
    writes = _writes(target)
    _write_all(library, scheduler, service, target, 13)
    assert writes == [owner.decision_id]
    selected = owner.selected_value
    assert type(selected) is dict and type(selected["value"]) is list
    held = library.held
    assert held is not None
    held.write(TargetDestination.AUTHORS, tuple(map(str, selected["value"])))
    return owner.decision_id


def _nothing_left_to_decide(library: Library) -> None:
    """The library now holds what the work's own evidence offers, and the
    providers name nothing: the next read of the work has nothing to ask."""
    held = library.held
    assert held is not None
    held.write(TargetDestination.TITLE, "Fixture Registry Title")
    held.write(TargetDestination.LANGUAGE, "English")
    held.providers = ()


def _library_notice(library: Library) -> RegenerationNotice | None:
    return library.root.regeneration_notice_store().read_regeneration_notice(
        _CONFIGURED
    )


def _work(library: Library) -> tuple[str, str | None, str | None]:
    (row,) = library.root._connection.execute(
        "SELECT state,outcome,failure_code FROM review_preparation_work"
    ).fetchall()
    return (str(row[0]), row[1], row[2])


def _scan_again(library: Library, at: int) -> None:
    library.root.request_review_scan("primary", "ebooks", "lib-1", PRODUCER, at)
    library.now[0] = at + 1
    library.drain()


@pytest.mark.parametrize(
    "ending",
    ["no_case_written_over_30_days", "failed_for_good"],
    ids=["no_case_written_over_30_days", "failed_for_good"],
)
def test_an_answer_whose_work_ends_without_a_case_stops_counting(
    tmp_path: Path, ending: str
) -> None:
    """The first scan since the regeneration completes with the work ended
    without a case: nothing left to decide and its write more than 30 days
    old (#1523), or a failure preparation does not retry. No case is made,
    so the question check never runs on it, and the answer stops counting
    (review round 2, M1)."""
    with prepared(
        tmp_path,
        automatic=True,
        library_model="publication",
        keeps_recent_writes=True,
    ) as library:
        answer = _written_answer(library, tmp_path)
        regenerate(library, _LATER, read_again=False)
        counting = _library_notice(library)
        assert counting is not None and counting.not_yet_checked == 1
        held = library.held
        assert held is not None
        if ending == "failed_for_good":
            held.failures.append("item_unreadable")
        else:
            _nothing_left_to_decide(library)

        _scan_again(library, _LATER)

        assert library.root._connection.execute(
            "SELECT state,discovery_failure FROM review_preparation_scans"
        ).fetchall() == [
            ("completed", None)
            if ending != "failed_for_good"
            else ("completed_with_failures", None)
        ]
        assert _work(library) == (
            ("complete", "no_case", None)
            if ending != "failed_for_good"
            else ("failed", None, "item_unreadable")
        )
        if ending != "failed_for_good":
            assert library.admissions[-1] == ("no_case", None)
        assert library.root._connection.execute(
            "SELECT count(*) FROM carry_outcomes WHERE answer_id=?", (answer,)
        ).fetchone() == (0,)
        stopped = dataclasses.replace(counting, not_yet_checked=0)
        assert _library_notice(library) == stopped

        # The next scan can make a case: the answer counts again while it
        # discovers, and stops again once it ends the same way.
        library.root.request_review_scan(
            "primary", "ebooks", "lib-1", PRODUCER, _LATER + 10
        )
        assert _library_notice(library) == counting
        if ending == "failed_for_good":
            held.failures.append("item_unreadable")
        _scan_again(library, _LATER + 10)
        assert _library_notice(library) == stopped


def test_an_answer_whose_work_is_still_preparing_counts_until_its_case_comes(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    """Control: a work whose extraction will be tried again is still
    preparing, so the answer counts, even where its scan stands completed
    over it. The retry makes a case, and while the check there still owes
    the answer its outcome (a store refusal, which the retry takes), the
    answer counts too; the final outcome ends the count."""
    with prepared(
        tmp_path,
        automatic=True,
        library_model="publication",
        keeps_recent_writes=True,
    ) as library:
        answer = _written_answer(library, tmp_path)
        regenerate(library, _LATER, read_again=False)
        counting = _library_notice(library)
        assert counting is not None and counting.not_yet_checked == 1
        held = library.held
        assert held is not None
        held.failures.append("transient")

        _scan_again(library, _LATER)

        assert _work(library) == ("delayed", None, "transient")
        assert _library_notice(library) == counting
        # A scan can stand closed over delayed work of its own until the next
        # claim pass reopens it (`recover_stranded_preparation_work`): the
        # work is still preparing, so the answer still counts.
        connection = library.root._connection
        connection.execute("UPDATE review_preparation_scans SET state='completed'")
        connection.commit()
        assert _library_notice(library) == counting

        (retry_at,) = connection.execute(
            "SELECT retry_not_before FROM review_preparation_work"
        ).fetchone()
        library.now[0] = int(retry_at) + 1
        with monkeypatch.context() as patch:
            patch.setattr(
                question_check_runner,
                "record_carry_outcome",
                _refused_by_the_store,
            )
            library.drain()

        assert _work(library) == ("complete", "case", None)
        assert connection.execute(
            "SELECT state,discovery_failure FROM review_preparation_scans"
        ).fetchall() == [("completed", None)]
        assert connection.execute(
            "SELECT count(*) FROM carry_outcomes WHERE answer_id=?", (answer,)
        ).fetchone() == (0,)
        assert _library_notice(library) == counting

        library.root.retry_question_checks(None, library.now[0])
        ((outcome,),) = connection.execute(
            "SELECT outcome FROM carry_outcomes WHERE answer_id=?", (answer,)
        ).fetchall()
        assert outcome not in PROVISIONAL_CARRY_OUTCOMES
        assert _library_notice(library) == dataclasses.replace(
            counting, kept=int(outcome == "carried"), not_yet_checked=0
        )


def _refused_by_the_store(*_args: object, **_kwargs: object) -> None:
    raise sqlite3.OperationalError("refused")


def test_an_answer_whose_library_is_no_longer_configured_stops_counting(
    tmp_path: Path,
) -> None:
    """With no scan since the regeneration, the answer counts while its
    library is configured and not once the settings no longer name it."""
    root = tmp_path / "data"
    root.mkdir(mode=0o700)
    path = root / "owner.sqlite"
    store, report, _ = _store(root, posture="preview")
    store.publish(report)
    store.decide("keep_current")
    resolved = store.resolved
    assert resolved is not None
    store.close()
    _regenerate(path, _FIRST_FINISHED)
    store = _reopened(root, resolved)
    try:
        notices = _notices(store)
        both = _CONFIGURED | {("primary", "audiobooks")}
        assert notices.read_regeneration_notice(both) == RegenerationNotice(
            1, 1, _FIRST_FINISHED, 0, 0, 1, False
        )
        for configured in (
            frozenset({("primary", "audiobooks")}),
            frozenset({("other", "ebooks")}),
            frozenset(),
        ):
            assert notices.read_regeneration_notice(configured) == RegenerationNotice(
                1, 1, _FIRST_FINISHED, 0, 0, 0, False
            )
    finally:
        store.close()
