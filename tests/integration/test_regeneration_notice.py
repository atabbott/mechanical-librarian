"""The upgrade notice's state across real regenerations (ADR-0108; contract
S14; #2040).

A book's title answer is held across `regenerate-derived` runs through the
command's own store, and the book is read again at the new epoch through the
real publication, admission and projection, where the question check runs.
`SQLiteRegenerationNoticeStore`, taken from the repository as C3 will take
it, reads the latest regeneration, what its first new cases did with the
answers given before it, and the one dismissal per regeneration.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from mechanical_librarian.adapters.persistence.ledger_meta import derived_epoch
from mechanical_librarian.adapters.persistence.regeneration import (
    SQLiteRegenerationStore,
)
from mechanical_librarian.application.configuration import ApplicationConfiguration
from mechanical_librarian.application.regenerate_derived import regenerate_derived
from mechanical_librarian.application.regeneration_notice import (
    RegenerationNotice,
    RegenerationNoticeDismissalInvalid,
    RegenerationNoticeStore,
)
from mechanical_librarian.domain.metadata_policy import (
    ResolvedMetadataPolicy,
    human_review_destinations,
)
from mechanical_librarian.domain.metadata_report import MetadataReport
from mechanical_librarian.domain.proposal_set import evaluate_report
from tests.support.ledger_partition import opens, rewrite
from tests.support.owner_values import OwnerStore, rewritten
from tests.unit.test_owner_answer_holds import _store

_FIRST_FINISHED = 1_700_000_000
_SECOND_FINISHED = 1_700_000_500


def _store_mode() -> ApplicationConfiguration:
    """No configuration file: the command reads the store alone."""
    raise FileNotFoundError


def _regenerate(path: Path, finished_at: int) -> None:
    """An upgrade's derived partition, regenerated by the command's store."""
    assert rewrite(path, "UPDATE ledger_meta SET derived_version=2") == 1
    outcome = regenerate_derived(
        SQLiteRegenerationStore(path, lambda: finished_at),
        retire_pending=False,
        configuration=_store_mode,
    )
    assert outcome.kind == "regenerated", outcome


def _reopened(root: Path, resolved: ResolvedMetadataPolicy) -> OwnerStore:
    store = OwnerStore(root, None)
    store.resolved = resolved
    return store


def _read_at_this_epoch(store: OwnerStore, report: MetadataReport) -> str:
    """Read the book again as a scan does after a regeneration: its
    proposals at the ledger's epoch, admitted and projected, so the question
    check runs on its first new case."""
    connection = store.repository._connection
    current = connection.execute(
        "SELECT report_id FROM current_metadata_reports WHERE connection_name=? "
        "AND library_name=? AND item_id=? AND file_identity=?",
        (
            report.target.connection,
            report.target.library,
            report.target.item,
            report.file.identity,
        ),
    ).fetchone()
    store.repository.publish(report, lambda: True, current and current[0])
    resolved = store.resolved
    assert resolved is not None
    proposal = evaluate_report(
        report,
        resolved.resolved_id,
        human_review_destinations(resolved),
        derived_epoch=derived_epoch(connection),
    )
    store.repository.publish_proposal(proposal)
    admitted = json.loads(store.repository.admit_review_case(proposal))
    assert admitted["status"] in {"admitted", "superseded"}, admitted
    case = store.load(admitted["review_case_id"])
    store.repository.persist_shadow_outcome(case.review_case_id, store.clock())
    return case.review_case_id


def _notices(store: OwnerStore) -> RegenerationNoticeStore:
    return store.repository.regeneration_notice_store()


def _outcomes(store: OwnerStore) -> list[tuple[str, int]]:
    return [
        tuple(row)
        for row in store.repository._connection.execute(
            "SELECT outcome,derived_epoch FROM carry_outcomes "
            "ORDER BY derived_epoch,checked_at"
        )
    ]


def test_no_regeneration_yet_reads_no_notice_and_dismisses_nothing(
    tmp_path: Path,
) -> None:
    store, report, _ = _store(tmp_path, posture="preview")
    try:
        store.publish(report)
        store.decide("keep_current")
        assert _notices(store).read_regeneration_notice() is None
        with pytest.raises(RegenerationNoticeDismissalInvalid):
            _notices(store).dismiss_regeneration_notice(1, _FIRST_FINISHED)
        assert store.repository._connection.execute(
            "SELECT count(*) FROM regeneration_notice_dismissals"
        ).fetchone() == (0,)
    finally:
        store.close()


def test_the_notice_counts_its_first_new_cases_and_a_second_regeneration_supersedes(
    tmp_path: Path,
) -> None:
    """Regeneration 1: the kept answer is not yet checked until its book is
    read again, then carried there (kept); a later case asking the carried
    answer again does not count. Its notice is dismissed once.
    Regeneration 2: the carried answer, given before it, meets a library
    whose title changed, so it is asked again, once however many cases ask;
    the new notice is its own, undismissed, and counts nothing of the
    first."""
    root = tmp_path / "data"
    root.mkdir(mode=0o700)
    path = root / "owner.sqlite"
    store, report, _ = _store(root, posture="preview")
    store.publish(report)
    store.decide("keep_current")
    resolved = store.resolved
    assert resolved is not None
    store.close()

    _regenerate(path, _FIRST_FINISHED)
    store = _reopened(root, resolved)
    try:
        assert _notices(store).read_regeneration_notice() == RegenerationNotice(
            regeneration_id=1,
            derived_epoch=1,
            finished_at=_FIRST_FINISHED,
            kept=0,
            asked_again=0,
            not_yet_checked=1,
            dismissed=False,
        )
        _read_at_this_epoch(store, report)
        assert _outcomes(store) == [("carried", 1)]
        first = _notices(store).read_regeneration_notice()
        assert first == RegenerationNotice(1, 1, _FIRST_FINISHED, 1, 0, 0, False)
        # The carried answer was given after the regeneration, so a later case
        # asking it again is no first new case of it.
        _read_at_this_epoch(store, rewritten(report, title="Another Title"))
        assert _outcomes(store) == [("carried", 1), ("target_changed", 1)]
        assert _notices(store).read_regeneration_notice() == first

        # One dismissal, never before the regeneration finished.
        with pytest.raises(RegenerationNoticeDismissalInvalid):
            _notices(store).dismiss_regeneration_notice(1, _FIRST_FINISHED - 1)
        with pytest.raises(RegenerationNoticeDismissalInvalid):
            _notices(store).dismiss_regeneration_notice(2, _FIRST_FINISHED)
        assert _notices(store).dismiss_regeneration_notice(1, _FIRST_FINISHED + 5)
        assert not _notices(store).dismiss_regeneration_notice(1, _FIRST_FINISHED + 9)
        assert store.repository._connection.execute(
            "SELECT regeneration_id,dismissed_at FROM regeneration_notice_dismissals"
        ).fetchall() == [(1, _FIRST_FINISHED + 5)]
        notice = _notices(store).read_regeneration_notice()
        assert notice is not None and notice.dismissed
    finally:
        store.close()
    assert opens(path)

    _regenerate(path, _SECOND_FINISHED)
    store = _reopened(root, resolved)
    try:
        second = _notices(store).read_regeneration_notice()
        assert second == RegenerationNotice(2, 2, _SECOND_FINISHED, 0, 0, 1, False)
        first_case = _read_at_this_epoch(
            store, rewritten(report, title="Another Title")
        )
        assert _outcomes(store)[2:] == [("target_changed", 2)]
        assert _notices(store).read_regeneration_notice() == RegenerationNotice(
            2, 2, _SECOND_FINISHED, 0, 1, 0, False
        )
        # Only the first new case counts: a later case of the same epoch
        # asking again leaves the counts as they are.
        _read_at_this_epoch(store, rewritten(report, title="Third Title"))
        assert _outcomes(store)[2:] == [("target_changed", 2)] * 2
        assert _notices(store).read_regeneration_notice() == RegenerationNotice(
            2, 2, _SECOND_FINISHED, 0, 1, 0, False
        )

        # Negative control: a field with nothing to answer on is not asked
        # again in the notice's count (contract R1), read on the derived fact.
        connection = store.repository._connection
        connection.execute(
            "UPDATE review_case_field_facts SET has_owner_decision_actions=0 "
            "WHERE review_case_id=? AND destination='title'",
            (first_case,),
        )
        notice = _notices(store).read_regeneration_notice()
        assert notice is not None and notice.asked_again == 0
    finally:
        store.close()
