"""The upgrade notice's state across real regenerations (ADR-0108; contract
S14; #2040).

A book's title answer is held across `regenerate-derived` runs through the
command's own store, and the book is read again at the new epoch through the
real publication, admission and projection, where the question check runs.
`SQLiteRegenerationNoticeStore`, taken from the repository as C3 will take
it, reads the latest regeneration, what its first new cases did with the
answers given before it, and the one dismissal per regeneration.
"""

