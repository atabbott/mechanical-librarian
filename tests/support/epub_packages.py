def _entry(name: str, data: bytes, compression: int) -> tuple[zipfile.ZipInfo, bytes]:
    info = zipfile.ZipInfo(name, (2026, 1, 13, 0, 0, 0))
    info.compress_type = compression
    info.create_system = 3
    info.external_attr = 0o100644 << 16
    info.flag_bits = 0x800
    return info, data


def epub_bytes(
    *,
    version: int = 3,
    container: bytes = CONTAINER_ONE,
    package: bytes | None = None,
    encryption: bytes | None = None,
    compression: int = zipfile.ZIP_DEFLATED,
    extra_entries: tuple[tuple[str, bytes, int], ...] = (),
    mimetype_value: bytes = b"application/epub+zip",
    mimetype_compression: int = zipfile.ZIP_STORED,
    mimetype_first: bool = True,
    include_default_content: bool = True,
) -> bytes:
    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", allowZip64=True) as archive:
        def write_mimetype() -> None:
            mimetype = zipfile.ZipInfo("mimetype", (2026, 1, 13, 0, 0, 0))
            mimetype.compress_type = mimetype_compression
            archive.writestr(mimetype, mimetype_value)

        if mimetype_first:
            write_mimetype()
        archive.writestr(*_entry("META-INF/container.xml", container, compression))
        archive.writestr(*_entry("EPUB/package.opf", package or (EPUB3_PACKAGE if version == 3 else EPUB2_PACKAGE), compression))
        if container is CONTAINER_MULTIPLE:
            archive.writestr(*_entry("EPUB/alternate.opf", EPUB3_PACKAGE, compression))
        if encryption is not None:
            archive.writestr(*_entry("META-INF/encryption.xml", encryption, compression))
        if include_default_content:
            archive.writestr(*_entry("EPUB/nav.xhtml", b"TRAP: navigation content must remain opaque", compression))
            archive.writestr(*_entry("EPUB/chapter.xhtml", b"TRAP: chapter content must remain opaque", compression))
            archive.writestr(*_entry("EPUB/toc.ncx", b"TRAP: NCX content must remain opaque", compression))
            archive.writestr(*_entry("EPUB/cover.jpg", b"TRAP: cover bytes must remain opaque", zipfile.ZIP_STORED))
        for name, data, compression in extra_entries:
            archive.writestr(*_entry(name, data, compression))
        if not mimetype_first:
            write_mimetype()
    return output.getvalue()


def epub_zip64_bytes() -> bytes:
    """Emit the bounded producer-forced ZIP64 local-header form."""

    output = io.BytesIO()
    with zipfile.ZipFile(output, "w", allowZip64=True) as archive:
        mimetype = zipfile.ZipInfo("mimetype", (2026, 1, 13, 0, 0, 0))
        mimetype.compress_type = zipfile.ZIP_STORED
        archive.writestr(mimetype, b"application/epub+zip")
        for name, data in (
            ("META-INF/container.xml", CONTAINER_ONE),
            ("EPUB/package.opf", EPUB3_PACKAGE),
        ):
            info, _ = _entry(name, data, zipfile.ZIP_DEFLATED)
            with archive.open(info, "w", force_zip64=True) as stream:
                stream.write(data)
        archive.writestr(*_entry("EPUB/nav.xhtml", b"opaque", zipfile.ZIP_DEFLATED))
        archive.writestr(*_entry("EPUB/chapter.xhtml", b"opaque", zipfile.ZIP_DEFLATED))
        archive.writestr(*_entry("EPUB/cover.jpg", b"opaque", zipfile.ZIP_STORED))
    return output.getvalue()


def epub_data_descriptor_bytes(
    *,
    descriptor_signature: bool = True,
    crc_signature_member: bool = False,
) -> bytes:
    """Emit a bounded archive whose non-mimetype entries use data descriptors."""

    members = [
        ("mimetype", b"application/epub+zip", zipfile.ZIP_STORED, False),
        ("META-INF/container.xml", CONTAINER_ONE, zipfile.ZIP_DEFLATED, True),
        ("EPUB/package.opf", EPUB3_PACKAGE, zipfile.ZIP_DEFLATED, True),
        ("EPUB/nav.xhtml", b"opaque", zipfile.ZIP_DEFLATED, True),
        ("EPUB/chapter.xhtml", b"opaque", zipfile.ZIP_DEFLATED, True),
        ("EPUB/cover.jpg", b"opaque", zipfile.ZIP_STORED, True),
    ]
    if crc_signature_member:
        # This four-byte synthetic payload has CRC-32 0x08074b50, the optional
        # data-descriptor signature, and exercises the legal ambiguous layout.
        members.append(("EPUB/crc-signature.bin", bytes.fromhex("ac0a7ad5"), zipfile.ZIP_STORED, True))
    body = bytearray()
    central = bytearray()
    for name, data, method, descriptor in members:
        raw_name = name.encode("ascii")
        compressed = data
        if method == zipfile.ZIP_DEFLATED:
            compressor = zlib.compressobj(level=6, wbits=-15)
            compressed = compressor.compress(data) + compressor.flush()
        crc = binascii.crc32(data) & 0xFFFFFFFF
        flags = 0x08 if descriptor else 0
        offset = len(body)
        body.extend(
            struct.pack(
                "<4s5H3L2H",
                b"PK\x03\x04",
                20,
                flags,
                method,
                0,
                0,
                0 if descriptor else crc,
                0 if descriptor else len(compressed),
                0 if descriptor else len(data),
                len(raw_name),
                0,
            )
        )
        body.extend(raw_name)
        body.extend(compressed)
        if descriptor:
            if descriptor_signature:
                body.extend(b"PK\x07\x08")
            body.extend(struct.pack("<3L", crc, len(compressed), len(data)))
        central.extend(
            struct.pack(
                "<4s6H3L5H2L",
                b"PK\x01\x02",
                20,
                20,
                flags,
                method,
                0,
                0,
                crc,
                len(compressed),
                len(data),
                len(raw_name),
                0,
                0,
                0,
                0,
                0,
                offset,
            )
        )
        central.extend(raw_name)
    central_offset = len(body)
    body.extend(central)
    body.extend(
        struct.pack(
            "<4s4H2LH",
            b"PK\x05\x06",
            0,
            0,
            len(members),
            len(members),
            len(central),
            central_offset,
            0,
        )
    )
    return bytes(body)


def _opening_package(
    *,
    version: int = 3,
    items: tuple[tuple[str, str, str, str], ...],
    spine: tuple[str, ...],
    guide: tuple[tuple[str, str], ...] = (),
) -> bytes:
    package_version = "3.0" if version == 3 else "2.0"
    manifest = "".join(
        f'<item id="{identity}" href="{href}" media-type="{media_type}"{properties}/>'
        for identity, href, media_type, properties in items
    )
    spine_xml = "".join(f'<itemref idref="{identity}"/>' for identity in spine)
    guide_xml = ""
    if guide:
        guide_xml = "<guide>" + "".join(
            f'<reference type="{role}" href="{href}"/>' for role, href in guide
        ) + "</guide>"
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<package xmlns="http://www.idpf.org/2007/opf" unique-identifier="pub-id" version="{package_version}">
  <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
    <dc:identifier id="pub-id">urn:uuid:00000000-0000-4000-8000-000000000007</dc:identifier>
    <dc:title>Fixture Registry Title</dc:title>
    <dc:language>en-GB</dc:language>
    {"<meta property=\"dcterms:modified\">2026-01-13T00:00:00Z</meta>" if version == 3 else ""}
  </metadata>
  <manifest>{manifest}</manifest>
  <spine>{spine_xml}</spine>
  {guide_xml}
</package>'''.encode("utf-8")


def _xhtml(body: str, *, title: str = "Synthetic opening matter") -> bytes:
    return f'''<?xml version="1.0" encoding="UTF-8"?>
<html xmlns="http://www.w3.org/1999/xhtml" xmlns:epub="http://www.idpf.org/2007/ops">
  <head><title>{title}</title></head><body>{body}</body>
</html>'''.encode("utf-8")


def _opening_epub(
    *,
    package: bytes,
    entries: tuple[tuple[str, bytes, int], ...],
    version: int = 3,
) -> bytes:
    return epub_bytes(
        version=version,
        package=package,
        extra_entries=entries,
        include_default_content=False,
    )


