#!/usr/bin/env python3
"""Record the exact Playwright headless Chromium payload before execution."""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import sys
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

from playwright.sync_api import sync_playwright

_SUPPORTED_PLATFORMS = ("darwin-arm64", "linux-x86_64")


class BrowserVerificationError(RuntimeError):
    """The installed qualification browser is absent or malformed.

    ``reason`` is the code reported to a caller. It exists because the four
    ways this fails are four different problems -- an unsupported machine, a
    layout the resolver could not read, a payload that is not there, and a
    payload that is there but malformed -- and collapsing them into one code
    left the reader of a failed `protected-browser` job with nothing to act on.
    """

    def __init__(self, reason: str) -> None:
        super().__init__(reason)
        self.reason = reason


def _platform_key() -> str:
    system = platform.system().lower()
    machine = platform.machine().lower()
    if system == "darwin" and machine == "arm64":
        return "darwin-arm64"
    if system == "linux" and machine in {"x86_64", "amd64"}:
        return "linux-x86_64"
    raise BrowserVerificationError("browser_platform_unsupported")


def _playwright_version() -> str:
    try:
        return version("playwright")
    except PackageNotFoundError:
        return "unknown"


def _installed_payload() -> tuple[Path, str]:
    with sync_playwright() as playwright:
        executable = Path(playwright.chromium.executable_path).resolve()
    chromium_root = next(
        (
            parent
            for parent in executable.parents
            if parent.name.startswith("chromium-")
            and parent.name.removeprefix("chromium-").isdigit()
        ),
        None,
    )
    if chromium_root is None:
        raise BrowserVerificationError("browser_payload_layout_unexpected")
    revision = chromium_root.name.removeprefix("chromium-")
    shell_root = chromium_root.parent / f"chromium_headless_shell-{revision}"
    payloads = sorted(shell_root.glob("chrome-headless-shell-*"))
    if len(payloads) != 1 or not payloads[0].is_dir():
        raise BrowserVerificationError("browser_payload_layout_unexpected")
    return payloads[0], revision


def browser_tree_sha256(payload: Path) -> str:
    if not payload.is_dir():
        raise BrowserVerificationError("browser_payload_absent")
    files = sorted(path for path in payload.rglob("*") if path.is_file())
    if not files or any(path.is_symlink() for path in payload.rglob("*")):
        raise BrowserVerificationError("browser_payload_invalid")
    digest = hashlib.sha256(b"playwright-browser-tree-v1\0")
    for path in files:
        relative = path.relative_to(payload).as_posix().encode("utf-8")
        digest.update(len(relative).to_bytes(4, "big"))
        digest.update(relative)
        size = path.stat().st_size
        digest.update(size.to_bytes(8, "big"))
        with path.open("rb") as stream:
            while chunk := stream.read(1024 * 1024):
                digest.update(chunk)
    return digest.hexdigest()


def browser_payload_evidence(
    payload: Path, key: str, revision: str
) -> dict[str, object]:
    """Describe the payload that is about to run the browser tier.

    The digest is recorded, not compared. Comparing it to a constant asserted
    only that the payload matched whatever a maintainer observed once, which
    under an auto-updating Playwright re-recorded itself on every bump while
    blocking each one until two platform hashes were regenerated by hand.

    Nothing here carries a filesystem path: this record is evidence and
    travels, so it states what ran rather than where it was found.
    """

    # Digest first: it is what rejects an absent or malformed payload, so the
    # counts below are only ever taken from a tree that has already passed.
    tree = browser_tree_sha256(payload)
    files = sorted(path for path in payload.rglob("*") if path.is_file())
    return {
        "chromium_revision": revision,
        "file_count": len(files),
        "platform": key,
        "playwright_version": _playwright_version(),
        "schema": "browser-payload-evidence-v1",
        "status": "recorded",
        "total_bytes": sum(path.stat().st_size for path in files),
        "tree_sha256": tree,
    }


def verify_playwright_browser() -> dict[str, object]:
    key = _platform_key()
    payload, revision = _installed_payload()
    return browser_payload_evidence(payload, key, revision)


def main(arguments: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--path", type=Path)
    parser.add_argument("--platform")
    parser.add_argument("--revision", default="unknown")
    values = parser.parse_args(arguments)
    key = values.platform or _platform_key()
    if key not in _SUPPORTED_PLATFORMS:
        raise BrowserVerificationError("browser_platform_unsupported")
    if values.path:
        record = browser_payload_evidence(values.path.resolve(), key, values.revision)
    else:
        record = verify_playwright_browser()
    print(json.dumps(record, sort_keys=True, separators=(",", ":")))
    return 0


def cli(arguments: list[str] | None = None) -> int:
    try:
        return main(arguments)
    except Exception as error:
        reason = getattr(error, "reason", "browser_verification_failed")
        print(
            json.dumps(
                {
                    "reason": reason,
                    "schema": "browser-payload-evidence-v1",
                    "status": "failed",
                },
                sort_keys=True,
                separators=(",", ":"),
            ),
            file=sys.stderr,
        )
        return 1


if __name__ == "__main__":
    raise SystemExit(cli())
